# tok_match: rsi=text rdi=kw rdx=len → rax=1 if prefix + boundary
tok_match:
    push    rbx
    push    rcx
    mov     rcx, rdx
    mov     rbx, rsi
tm_loop:
    test    rcx, rcx
    jz      tm_bound
    mov     al, [rbx]
    mov     dl, [rdi]
    cmp     al, dl
    jne     tm_no
    inc     rbx
    inc     rdi
    dec     rcx
    jmp     tm_loop
tm_bound:
    mov     al, [rbx]
    cmp     al, ' '
    je      tm_yes
    cmp     al, '"'
    je      tm_yes
    cmp     al, 0
    je      tm_yes
    cmp     al, 9
    je      tm_yes
    cmp     al, '{'
    je      tm_yes
    jmp     tm_no
tm_yes:
    mov     rax, 1
    pop     rcx
    pop     rbx
    ret
tm_no:
    xor     rax, rax
    pop     rcx
    pop     rbx
    ret
