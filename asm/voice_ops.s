    push    rbx
    lea     rbx, [rip+linebuf]
edn_find:
    cmp     byte ptr [rbx], 0
    je      edn_fail
    cmp     byte ptr [rbx], 't'
    jne     edn_inc
    cmp     byte ptr [rbx+1], 'o'
    jne     edn_inc
    cmp     byte ptr [rbx+2], ' '
    je      edn_tok
    cmp     byte ptr [rbx+2], '\t'
    je      edn_tok
edn_inc:
    inc     rbx
    jmp     edn_find
edn_tok:
    add     rbx, 3
edn_ws:
    mov     al, [rbx]
    cmp     al, ' '
    je      edn_wsi
    cmp     al, '\t'
    je      edn_wsi
    jmp     edn_copy
edn_wsi:
    inc     rbx
    jmp     edn_ws
edn_copy:
    lea     rdi, [rip+name_buf]
    xor     rcx, rcx
