# ---------- copy ----------
do_copy:
    # voice copy from "SRC" to DST  — first quote=SRC, name after to
    lea     rdi, [rip+linebuf]
    call    extract_quote
    test    rax, rax
    jz      copy_fail
    mov     rsi, rax
    mov     r12, rcx
    lea     rdi, [rip+wav_path]
    xor     r13, r13
copy_src:
    cmp     r13, r12
    jge     copy_src_d
    cmp     r13, 510
    jge     copy_src_d
    mov     al, [rsi+r13]
    mov     [rdi+r13], al
    inc     r13
    jmp     copy_src
copy_src_d:
    mov     byte ptr [rdi+r13], 0
    call    extract_dst_name
    test    rax, rax
    jz      copy_fail
    # open + parse SRC
    lea     rdi, [rip+wav_path]
    mov     rsi, O_RDONLY
    xor     rdx, rdx
    call    sys_open
    cmp     rax, 0
    jl      copy_fail
    mov     r12, rax
    mov     rdi, r12
    lea     rsi, [rip+wav_buf]
    mov     rdx, WAV_CAP
    call    sys_read
    mov     qword ptr [rip+wav_len], rax
    mov     rdi, r12
    call    sys_close
    cmp     qword ptr [rip+wav_len], 44
    jl      copy_fail
    call    parse_wav_metrics
    test    rax, rax
    jz      copy_fail
    call    write_voice_model_tree
    lea     rsi, [rip+msg_arrow]
    mov     rdx, msg_arrow_len
    call    write_stdout
    lea     rsi, [rip+path_build]
    call    strlen
    mov     rdx, rax
    lea     rsi, [rip+path_build]
    call    write_stdout
    lea     rax, [rip+path_build]
    mov     rcx, rdx
    call    set_last_from_rcx
    call    bind_arrow_from_line
    lea     rsi, [rip+msg_nl]
    mov     rdx, 1
    call    write_stdout
    jmp     vod_done
copy_fail:
    lea     rsi, [rip+err_copy_src]
    mov     rdx, err_copy_src_len
    call    write_stdout
    mov     edi, 1
    call    sys_exit

