# Second token after "voice" (avoid path substrings like sample_review)
voice_ops_dispatch:
    push    rbx
    push    r12
    push    r13
    push    r14

    call    voice_second_token      # rax=ptr to token or 0
    test    rax, rax
    jz      vod_session
    mov     rbx, rax

    mov     rsi, rbx
    lea     rdi, [rip+needle_review]
    mov     rdx, 6
    call    tok_match
    test    rax, rax
    jnz     do_review

    mov     rsi, rbx
    lea     rdi, [rip+needle_code]
    mov     rdx, 4
    call    tok_match
    test    rax, rax
    jnz     do_code

    mov     rsi, rbx
    lea     rdi, [rip+needle_copy]
    mov     rdx, 4
    call    tok_match
    test    rax, rax
    jnz     do_copy

    mov     rsi, rbx
    lea     rdi, [rip+needle_pstn]
    mov     rdx, 4
    call    tok_match
    test    rax, rax
    jnz     do_pstn

    mov     rsi, rbx
    lea     rdi, [rip+needle_model]
    mov     rdx, 5
    call    tok_match
    test    rax, rax
    jnz     do_model_cmd

vod_session:
    # bare voice { … }
    lea     rsi, [rip+msg_session]
    mov     rdx, msg_session_len
    call    write_stdout
    jmp     vod_done

# ---------- review ----------
do_review:
    lea     rdi, [rip+linebuf]
    call    extract_quote
    test    rax, rax
    jz      rev_use_fix
    mov     rsi, rax
    mov     r12, rcx
    lea     rdi, [rip+wav_path]
    xor     r13, r13
rev_cp:
    cmp     r13, r12
    jge     rev_cp_done
    cmp     r13, 510
    jge     rev_cp_done
    mov     al, [rsi+r13]
    mov     [rdi+r13], al
    inc     r13
    jmp     rev_cp
rev_cp_done:
    mov     byte ptr [rdi+r13], 0
    jmp     rev_open
rev_use_fix:
    lea     rsi, [rip+fixture_wav]
    lea     rdi, [rip+wav_path]
    call    copy_cstr
rev_open:
    lea     rdi, [rip+wav_path]
    mov     rsi, O_RDONLY
    xor     rdx, rdx
    call    sys_open
    cmp     rax, 0
    jl      rev_fail_open
    mov     r12, rax
    mov     rdi, r12
    lea     rsi, [rip+wav_buf]
    mov     rdx, WAV_CAP
    call    sys_read
    cmp     rax, 44
    jl      rev_fail_wav
    mov     qword ptr [rip+wav_len], rax
    mov     rdi, r12
    call    sys_close
    call    parse_wav_metrics
    test    rax, rax
    jz      rev_fail_wav
    call    build_review_json
    lea     rsi, [rip+msg_arrow]
    mov     rdx, msg_arrow_len
    call    write_stdout
    lea     rsi, [rip+report_buf]
    call    strlen
    mov     rdx, rax
    lea     rsi, [rip+report_buf]
    call    write_stdout
    lea     rax, [rip+report_buf]
    mov     rcx, rdx
    call    set_last_from_rcx
    call    bind_arrow_from_line
    lea     rsi, [rip+msg_nl]
    mov     rdx, 1
    call    write_stdout
    jmp     vod_done
rev_fail_open:
    lea     rsi, [rip+err_review_open]
    mov     rdx, err_review_open_len
    call    write_stdout
    mov     edi, 1
    call    sys_exit
rev_fail_wav:
    lea     rsi, [rip+err_not_wav]
    mov     rdx, err_not_wav_len
    call    write_stdout
    mov     edi, 1
    call    sys_exit

